DROP TABLE IF EXISTS customer;
DROP TABLE IF EXISTS account;
DROP TABLE IF EXISTS txn;
DROP TABLE IF EXISTS alert;
DROP TABLE IF EXISTS aml_case;
CREATE TABLE customer (
  customer_id TEXT PRIMARY KEY, name TEXT, name_kana TEXT, birth_date TEXT, address TEXT,
  occupation TEXT, employer TEXT, declared_income INTEGER, purpose TEXT, risk_rating TEXT, customer_since TEXT);
CREATE TABLE account (
  account_id TEXT PRIMARY KEY, customer_id TEXT, branch TEXT, type TEXT, opened_on TEXT);
CREATE TABLE txn (
  id INTEGER PRIMARY KEY AUTOINCREMENT, account_id TEXT, txn_date TEXT, kind TEXT,
  amount INTEGER, counterparty TEXT, channel TEXT, memo TEXT);
CREATE TABLE alert (
  alert_id TEXT PRIMARY KEY, account_id TEXT, raised_on TEXT, rule TEXT, detail TEXT, status TEXT);
CREATE TABLE aml_case (
  context_id TEXT PRIMARY KEY, alert_id TEXT, step TEXT, recommendation TEXT,
  decision TEXT, note TEXT, decision_id TEXT, updated_at TEXT);


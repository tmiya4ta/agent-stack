def q(v):
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def row(table, vals):
    return f"insert into {table} values ({', '.join(q(v) for v in vals)});"



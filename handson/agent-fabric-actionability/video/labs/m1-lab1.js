// Lab 1-1 Agent Scanner
s.lib();
await s.login();
await s.watchAws();
await s.intro('1-1', 'Agent Scanner で外部のエージェントを取り込む');
await s.bg(s.V['Anypoint/ユーザー名'], { narrate: '左下のビジネスグループの切り替えで、ご自身のビジネスグループ (ご自身のユーザー名と同じ名前) を選択します' });
await s.step('左のメニューの Agents を開き、右上の Add Agent から Connect to Provider を選択します', 600);
await s.click(page.getByRole('link', { name: 'Agents' }).first()); await page.waitForTimeout(4000);
await s.click(page.getByRole('button', { name: /Add Agent/ })); await page.waitForTimeout(1500);
await s.shot('02-add-agent');
await s.click(page.getByText('Connect to Provider').first()); await page.waitForTimeout(3500);
await s.step('プロバイダーの一覧から Amazon を選択し、Continue をクリックします', 600);
await s.click(page.getByText('Amazon', { exact: true }).first()); await page.waitForTimeout(800);
await s.shot('02-provider-amazon');
await s.click(page.getByRole('button', { name: 'Continue' })); await page.waitForTimeout(3000);
await s.step('Platform に Amazon Bedrock を選択し、講師がご案内したアクセスキーとリージョン (us-east-1) を入力します', 600);
await s.click(page.getByText('Amazon Bedrock', { exact: true }));
const k = page.locator('#keyId'), sec = page.locator('#keySecret');
await s.blur(k); await s.blur(sec);
await s.type(k, s.V['Bedrock/AWS Access Key ID'], { delay: 25 });
await s.type(sec, s.V['Bedrock/AWS Secret Access Key'], { delay: 15 });
await s.click(page.locator('#region')); await page.waitForTimeout(1000);
await s.click(page.getByRole('option', { name: /us-east-1/ }).first()); await page.waitForTimeout(800);
await s.step('Test Connection をクリックします。Connection successful と表示されれば、接続できています', 600);
await s.click(page.getByRole('button', { name: 'Test Connection' }));
await page.getByText('Connection successful').first().waitFor({ timeout: 30000 }); await page.waitForTimeout(2500);
await s.shot('02-test-connection');
await s.step('Continue をクリックし、Scanner の名前を「demo Scanner」にします。頻度と時刻は既定のままです', 600);
await s.click(page.getByRole('button', { name: 'Continue' })); await page.waitForTimeout(2500);
await s.type(page.locator('#ap-step-connection-name'), 'demo Scanner');
await page.waitForTimeout(1200);
await s.shot('02-connection-filled');
await s.step('Connect をクリックすると、Scanner が作成されます', 600);
await s.click(page.getByRole('button', { name: 'Connect', exact: true }));
await page.getByText(/We've created a Scanner/).first().waitFor({ timeout: 30000 }); await page.waitForTimeout(3000);
await s.shot('02-connected');
await s.step('左のメニューの Providers を開き、作成した Scanner を選択します', 600);
await s.click(page.getByRole('link', { name: 'Providers' }).first()); await page.waitForTimeout(4000);
await s.click(page.getByText('demo Scanner').first()); await page.waitForTimeout(4000);
await s.shot('02-scanner');
await s.step('Run Discovery Scan をクリックして、スキャンを開始します', 600);
await s.click(page.getByRole('button', { name: 'Run Discovery Scan' })); await page.waitForTimeout(4000);
await s.step('スキャンは 1 分ほどで完了します。結果が表示されない場合は、画面を再読み込みします', 3000);
s.skipStart();
for (let i = 0; i < 12; i++) {
  await page.waitForTimeout(15000);
  await page.reload({ waitUntil: 'domcontentloaded' }); await page.waitForTimeout(6000);
  if (await page.getByText('Success', { exact: true }).first().isVisible().catch(() => false)) break;
}
await s.closeAgent();
s.skipEnd();
await s.step('Scan History に Success と表示されました。結果の行を開きます', 600);
await s.click(page.getByText('Success', { exact: true }).first()); await page.waitForTimeout(3000);
await s.watchAws();
await s.step('Services Added に、取り込まれたエージェントが表示されます', 2500);
await s.shot('02-scan-details');
await s.step('取り込まれたエージェントを開きます', 600);
await s.click(page.getByText(/agent-quick-start/).first()); await page.waitForTimeout(6000);
await s.watchAws();
await s.step('Exchange に登録されたエージェントのページです。上から順に確認します', 2500);
await s.shot('02-agent-detail');
await s.step('Documentation には、作成日時、バージョン、AWS のアカウント ID、Provider URL が表示されます', 3500);
await s.scrollTo(page.getByRole('heading', { name: 'Agent card' }), 'start');
await s.step('Agent card には、エージェントの ID、エンドポイントの URL とリージョン、プロトコル、機能が表示されます。ほかのエージェントや Broker が呼び出すための「名刺」に当たります', 5500);
await s.scrollTo(page.getByRole('heading', { name: 'Agent configuration' }), 'start');
await s.shot('02-agent-configuration');
await s.step('Agent configuration には、基盤モデル (Claude 3.5 Haiku)、状態、エイリアス、ARN など、Amazon Bedrock 固有の項目が表示されます', 5000);
await s.scrollTo(page.getByRole('heading', { name: 'System instructions' }), 'start');
await s.step('System instructions の View をクリックすると、エージェントへの指示 (プロンプト) が表示されます', 600);
await s.click(page.getByRole('button', { name: 'View' }).last()); await page.waitForTimeout(2500);
await s.scrollTo(page.getByRole('heading', { name: 'System instructions' }), 'start');
await s.shot('02-system-instructions');
await s.step('Vogue Premiere の会員向けの Loyalty Agent であることがわかります。ほかのクラウドで動いているエージェントも、Anypoint の中で内容を確認できます', 6000);
return 'ok';

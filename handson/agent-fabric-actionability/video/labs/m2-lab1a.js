// Lab 2-1 MCP Bridge (前半: Anypoint で MCP サーバーを作る)
s.lib();
await s.login();
await s.intro('2-1', 'MCP Bridge で 2 つの API を 1 つの MCP サーバーにする');
await s.bg(s.V.WS, { narrate: `左下のビジネスグループの切り替えで、${s.V.WS} (一覧の 2 番目) を選択します` });
await s.step('左のメニューの MCP Servers を開き、右上の Add MCP Server から Create MCP Server を選択します', 600);
await s.click(page.getByRole('link', { name: 'MCP Servers' }).first()); await page.waitForTimeout(4000);
await s.click(page.getByRole('button', { name: /Add MCP Server/ })); await page.waitForTimeout(1500);
await s.shot('03-add-mcp-menu');
await s.click(page.getByText('Create MCP Server').first()); await page.waitForTimeout(5000);
await s.step('APIs (2) で絞り込み、Customer REST API と Order REST API の両方を選択します', 600);
await s.click(page.getByText('APIs (2)')); await page.waitForTimeout(2000);
await s.click(page.getByText('Customer REST API', { exact: true })); await page.waitForTimeout(2000);
await s.click(page.getByText('Order REST API', { exact: true })); await page.waitForTimeout(2500);
await s.shot('03-select-apis');
await s.step('右側に、2 つの API の操作がツールとして表示されます。6 つのツールをすべて選択したまま、Next をクリックします', 3500);
await s.click(page.getByRole('button', { name: /Next/ })); await page.waitForTimeout(4000);
await s.step('Review の画面です。右上の Edit をクリックして、サーバーの設定を開きます', 1500);
await s.shot('03-review');
await s.click(page.getByRole('button', { name: 'Edit server configuration' })); await page.waitForTimeout(2000);
const dlg = page.getByRole('dialog');
await s.step('Server Name を commerce-mcp-demo にします。Path は名前から自動で設定されます', 600);
await s.type(dlg.locator('input').first(), 'commerce-mcp-demo');
await page.waitForTimeout(1500);
await s.step('Gateway を、既定の agent-network-gw から attendee-gateway (sandbox) に変更します', 600);
await s.click(dlg.getByRole('combobox').filter({ hasText: /gw|gateway/ })); await page.waitForTimeout(1200);
await s.click(page.getByRole('option', { name: /attendee-gateway/ })); await page.waitForTimeout(1500);
await s.step('agent-network-gw は、全員で共有している Vogue Premiere の Broker が使用しているため、必ず attendee-gateway を選びます', 3500);
await s.shot('03-server-config-filled');
await s.step('Save をクリックします', 600);
await s.click(dlg.getByRole('button', { name: 'Save' })); await page.waitForTimeout(2500);
await s.step('Create & Deploy をクリックして、MCP サーバーを作成し、ゲートウェイにデプロイします', 600);
await s.click(page.getByRole('button', { name: 'Create & Deploy' }));
s.skipStart();
await page.waitForURL(/mcp-servers\/commerce-mcp-demo/, { timeout: 180000 }).catch(() => {});
await page.waitForTimeout(8000);
await s.closeAgent();
s.skipEnd();
await s.step('MCP サーバーが作成されました。Tools & Sources に、2 つの API と 6 つのツールが表示されています', 4000);
await s.shot('03-deployed');
return page.url();
